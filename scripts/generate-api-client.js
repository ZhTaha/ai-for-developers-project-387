#!/usr/bin/env node

// Генерирует браузерный SDK из TypeSpec → OpenAPI. Выходной файл не редактируется вручную.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const input = path.join(root, 'typespec', 'generated', 'openapi.json');
const output = path.join(root, 'public', 'generated-api.js');
const spec = JSON.parse(fs.readFileSync(input, 'utf8'));

const operations = [
  ['listEventTypes', 'get', '/api/event-types'],
  ['createEventType', 'post', '/api/event-types'],
  ['deleteEventType', 'delete', '/api/event-types/{id}'],
  ['getAvailability', 'get', '/api/availability'],
  ['updateAvailability', 'put', '/api/availability'],
  ['listSlots', 'get', '/api/slots'],
  ['listBookings', 'get', '/api/bookings'],
  ['createBooking', 'post', '/api/bookings'],
  ['deleteBooking', 'delete', '/api/bookings/{id}'],
];

for (const [, method, route] of operations) {
  if (!spec.paths?.[route]?.[method]) {
    throw new Error(`OpenAPI does not contain ${method.toUpperCase()} ${route}`);
  }
}

function typeFor(schema) {
  if (schema.$ref) return schema.$ref.split('/').at(-1);
  if (schema.type === 'array') return `${typeFor(schema.items)}[]`;
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  return 'string';
}

const typeDefinitions = Object.entries(spec.components.schemas)
  .filter(([, schema]) => schema.type === 'object')
  .map(([name, schema]) => {
    const required = new Set(schema.required || []);
    const properties = Object.entries(schema.properties || {})
      .map(([property, value]) => ` * @property {${typeFor(value)}} ${property}${required.has(property) ? '' : ' (optional)'}`)
      .join('\n');
    return `/**\n * @typedef {Object} ${name}\n${properties}\n */`;
  })
  .join('\n\n');

const client = `// This file is generated by scripts/generate-api-client.js from typespec/generated/openapi.json.
// Do not edit it manually. Run: mise run generate

${typeDefinitions}

export class ApiError extends Error {
  constructor(status, message) {
    super(message);
    this.name = 'ApiError';
    this.status = status;
  }
}

export class CalendarApiClient {
  constructor(baseUrl = '/api') {
    this.baseUrl = baseUrl;
  }

  async request(path, options = {}) {
    const response = await fetch(\`${'${this.baseUrl}'}\${path}\`, {
      headers: { 'Content-Type': 'application/json', ...options.headers },
      ...options,
    });
    if (response.status === 204) return undefined;
    const body = await response.json();
    if (!response.ok) throw new ApiError(response.status, body.error || response.statusText);
    return body;
  }

  listEventTypes() { return this.request('/event-types'); }
  createEventType(body) { return this.request('/event-types', { method: 'POST', body: JSON.stringify(body) }); }
  deleteEventType(id) { return this.request(\`/event-types/\${encodeURIComponent(id)}\`, { method: 'DELETE' }); }
  getAvailability() { return this.request('/availability'); }
  updateAvailability(body) { return this.request('/availability', { method: 'PUT', body: JSON.stringify(body) }); }
  listSlots(date, eventTypeId) {
    const query = new URLSearchParams({ date, eventTypeId });
    return this.request(\`/slots?\${query}\`);
  }
  listBookings() { return this.request('/bookings'); }
  createBooking(body) { return this.request('/bookings', { method: 'POST', body: JSON.stringify(body) }); }
  deleteBooking(id) { return this.request(\`/bookings/\${encodeURIComponent(id)}\`, { method: 'DELETE' }); }
}
`;

fs.writeFileSync(output, client);
